// Regenerate the plain examples from the Helm source of truth. Never contacts a cluster.
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
for (const name of ['crap', 'cliproxy']) {
  const args = ['template', name, 'k8s/helm/' + name, '--namespace', 'crap', '--kube-version', '1.30.0'];
  const output = '# Generated by node k8s/render.mjs; customize a copy for your cluster.\n' + execFileSync('helm', args, {cwd: root, encoding: 'utf8'}).replace(/\r\n/g, '\n');
  const file = new URL('manifests/' + name + '.yaml', import.meta.url);
  if (check) {
    if ((await readFile(file, 'utf8')).replace(/\r\n/g, '\n') !== output) throw new Error('Stale plain manifests: run node k8s/render.mjs');
  } else await writeFile(file, output);
}
console.log(check ? 'Plain manifests match both Helm charts.' : 'Plain manifests regenerated; no cluster changes.');
