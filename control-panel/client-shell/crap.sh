# CRAP shell integration for Bash and Zsh. Source this file; no new runtime needed.
# Install: source ./crap.sh install bash   (or: source ./crap.sh install zsh)
if [ -n "${BASH_VERSION-}" ]; then crap_source_file=${BASH_SOURCE[0]}; elif [ -n "${ZSH_VERSION-}" ]; then eval 'crap_source_file=${(%):-%x}'; fi

_crap_root() { printf '%s' "${CRAP_SHELL_HOME:-$HOME/.local/share/crap}"; }
_crap_dir() { printf '%s/clients/claude' "$(_crap_root)"; }
_crap_mode() { if [ -f "$(_crap_dir)/mode" ]; then cat "$(_crap_dir)/mode"; else printf direct; fi; }
_crap_write() (
    umask 077
    local temp
    temp=$(mktemp "${1}.XXXXXX") || return 1
    printf '%s' "$2" > "$temp" && mv -f "$temp" "$1"
)
_crap_endpoint_ok() {
    printf '%s\n' "$1" | LC_ALL=C grep -Eq '^(https://[A-Za-z0-9][A-Za-z0-9.-]*(:[0-9]{1,5})?|http://(localhost|127\.0\.0\.1)(:[0-9]{1,5})?)$'
}
_crap_configure() (
    umask 077
    local endpoint key echo_state
    printf 'Claude API origin (no /v1): '
    IFS= read -r endpoint || return 1
    endpoint=${endpoint%/}
    _crap_endpoint_ok "$endpoint" || { printf '%s\n' 'Use an HTTPS origin or loopback HTTP, without a path, credentials or query.' >&2; return 1; }
    [ -t 0 ] || { printf '%s\n' 'Enter the key in an interactive terminal; it is never accepted as a command argument.' >&2; return 1; }
    echo_state=$(stty -g) || return 1
    trap 'stty "$echo_state"' EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    printf 'CRAP client API key (input hidden): '
    stty -echo
    IFS= read -r key
    stty "$echo_state"
    printf '\n'
    printf '%s\n' "$key" | LC_ALL=C grep -Eq '^[A-Za-z0-9_.:-]+$' || { printf '%s\n' 'Unsupported key format. Use a client API key generated by CRAP.' >&2; return 1; }
    _crap_write "$(_crap_dir)/key" "$key" && _crap_write "$(_crap_dir)/endpoint" "$endpoint" || return 1
    printf '%s\n' 'Connection saved. Select proxy mode when ready.'
)
_crap_use() {
    [ "$1" = claude ] && { [ "$2" = direct ] || [ "$2" = proxy ]; } || { printf '%s\n' 'Supported: crap use claude direct|proxy' >&2; return 1; }
    if [ "$2" = proxy ]; then
        [ -s "$(_crap_dir)/key" ] && [ -s "$(_crap_dir)/endpoint" ] || { printf '%s\n' 'Run crap configure claude first.' >&2; return 1; }
    fi
    _crap_write "$(_crap_dir)/mode" "$2" || return 1
    printf 'Claude Code: %s. Applies to new launches; keep using claude.\n' "$2"
}
_crap_enroll() {
    local panel ticket mode cleanup source_file result
    panel=$1; ticket=$2; mode=$3; cleanup=$4; source_file=$5
    _crap_endpoint_ok "$panel" || return 1
    command -v curl >/dev/null 2>&1 || { printf '%s\n' 'Automatic setup requires curl.' >&2; return 1; }
    # Keep the ticket off the command line, and credentials out of terminal output.
    (
        umask 077
        local body code marker endpoint key extra
        body=$(mktemp "$(_crap_dir)/enroll.XXXXXX") || exit 1
        trap 'rm -f "$body"' EXIT
        trap 'exit 130' INT
        trap 'exit 143' TERM
        code=$(printf '%s' "$ticket" | curl --silent --output "$body" --write-out '%{http_code}' --header 'Content-Type: text/plain' --data-binary @- "$panel/client-setup/redeem")
        [ "$code" = 200 ] || exit 1
        { IFS= read -r marker; IFS= read -r endpoint; IFS= read -r key; IFS= read -r extra || :; } < "$body"
        [ "$marker" = CRAP-ENROLLMENT-1 ] && [ -z "$extra" ] && _crap_endpoint_ok "$endpoint" || exit 1
        printf '%s\n' "$key" | LC_ALL=C grep -Eq '^crap-[a-f0-9]{48}$' || exit 1
        # Keep launches direct until both parts of the new connection are saved.
        _crap_write "$(_crap_dir)/mode" direct || exit 1
        _crap_write "$(_crap_dir)/key" "$key" && _crap_write "$(_crap_dir)/endpoint" "$endpoint" && _crap_use claude "$mode"
    )
    result=$?
    ticket=''
    if [ "$result" != 0 ]; then
        printf '%s\n' 'Automatic setup failed. Check Tailscale and the 15-minute expiry. If consumed, remove this device in Client API Keys and download a new installer.' >&2
        return 1
    fi
    printf '%s\n' 'Proxy connection configured. Keep using claude; use crap to switch modes.'
    if [ "$cleanup" = yes ] && [ "$source_file" != "$(_crap_root)/shell.sh" ]; then
        rm -f -- "$source_file" || printf '%s\n' 'Setup succeeded. You can delete the downloaded installer manually.'
    fi
    if [ -t 0 ]; then _crap_menu; fi
    return 0
}
_crap_status() {
    local client
    printf 'Claude Code: %s (supported)\n' "$(_crap_mode)"
    for client in codex gemini; do
        if command -v "$client" >/dev/null 2>&1; then printf '%s: installed; adapter not supported yet\n' "$client"; else printf '%s: not installed; adapter not supported yet\n' "$client"; fi
    done
    if [ -f "$(_crap_dir)/endpoint" ]; then printf 'Proxy: %s\n' "$(cat "$(_crap_dir)/endpoint")"; fi
    printf '%s\n' 'History: existing Claude profile. Direct mode preserves your original Claude environment and login.'
}
_crap_doctor() (
    umask 077
    local dir endpoint key header body code
    dir=$(_crap_dir)
    endpoint=$(cat "$dir/endpoint") || return 1
    key=$(cat "$dir/key") || return 1
    _crap_endpoint_ok "$endpoint" || return 1
    printf '%s\n' "$key" | LC_ALL=C grep -Eq '^[A-Za-z0-9_.:-]+$' || return 1
    command -v curl >/dev/null 2>&1 || { printf '%s\n' 'Connection check requires curl.' >&2; return 1; }
    header=$(mktemp "$dir/header.XXXXXX") || return 1
    body=$(mktemp "$dir/response.XXXXXX") || { rm -f "$header"; return 1; }
    trap 'rm -f "$header" "$body"' EXIT
    printf 'Authorization: Bearer %s\n' "$key" > "$header"
    code=$(curl --silent --output "$body" --write-out '%{http_code}' --header "@$header" "$endpoint/v1/models")
    if [ "$code" = 200 ] && grep -q '"data"' "$body"; then
        printf '%s\n' 'Proxy authenticated. No inference request sent.'
    else
        printf '%s\n' 'Proxy check failed. Check the client key, endpoint, and Tailscale connection.' >&2
        return 1
    fi
)
_crap_claude() (
    # A subshell confines all routing variables and cleanup to this launch.
    local dir executable mode argument endpoint key settings rc
    dir=$(_crap_dir)
    executable=$(cat "$dir/executable") || return 1
    [ -x "$executable" ] || { printf '%s\n' 'Claude executable moved. Reinstall CRAP shell integration.' >&2; return 1; }
    mode=$(_crap_mode)
    if [ "$mode" = direct ]; then "$executable" "$@"; return $?; fi
    [ "$mode" = proxy ] || { printf '%s\n' 'Invalid mode. Run crap use claude direct|proxy.' >&2; return 1; }
    for argument in "$@"; do
        case "$argument" in --settings|--settings=*|--setting-sources|--setting-sources=*) printf '%s\n' 'Proxy mode reserves --settings. Use direct mode for custom settings files.' >&2; return 1;; esac
    done
    if [ -e /etc/claude-code/managed-settings.json ] || [ -e '/Library/Application Support/ClaudeCode/managed-settings.json' ]; then
        printf '%s\n' 'Managed Claude settings detected. Ask your administrator to configure routing; CRAP will not override them.' >&2
        return 1
    fi
    endpoint=$(cat "$dir/endpoint") || return 1
    key=$(cat "$dir/key") || return 1
    _crap_endpoint_ok "$endpoint" || return 1
    printf '%s\n' "$key" | LC_ALL=C grep -Eq '^[A-Za-z0-9_.:-]+$' || return 1
    umask 077
    settings=$(mktemp "$dir/session.XXXXXX") || return 1
    trap 'rm -f "$settings"' EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    printf '{"env":{"ANTHROPIC_BASE_URL":"%s","ANTHROPIC_AUTH_TOKEN":"%s","ANTHROPIC_API_KEY":"","CLAUDE_CODE_OAUTH_TOKEN":"","CLAUDE_CODE_USE_BEDROCK":"","CLAUDE_CODE_USE_VERTEX":"","CLAUDE_CODE_USE_FOUNDRY":""}}' "$endpoint" "$key" > "$settings"
    export ANTHROPIC_BASE_URL="$endpoint" ANTHROPIC_AUTH_TOKEN="$key"
    unset ANTHROPIC_API_KEY CLAUDE_CODE_OAUTH_TOKEN CLAUDE_CODE_USE_BEDROCK CLAUDE_CODE_USE_VERTEX CLAUDE_CODE_USE_FOUNDRY
    "$executable" --settings "$settings" "$@"
    rc=$?
    return "$rc"
)
_crap_uninstall() {
    local root profile loader temp answer
    printf 'Remove integration and its saved proxy key? Type REMOVE: '
    IFS= read -r answer
    [ "$answer" = REMOVE ] || return 0
    root=$(_crap_root)
    profile=$(cat "$root/profile") || return 1
    loader=$(cat "$root/loader") || return 1
    if [ -f "$profile" ]; then
        temp=$(mktemp "$root/profile.XXXXXX") || return 1
        # Compare complete lines literally; do not interpret the loader as code or a regex.
        awk -v line="$loader" '$0 != line' "$profile" > "$temp" && cat "$temp" > "$profile"
        rm -f "$temp"
    fi
    _crap_write "$(_crap_dir)/mode" direct
    rm -f "$(_crap_dir)/key" "$(_crap_dir)/endpoint"
    unset -f claude crap
    printf '%s\n' 'Shell loader and proxy credentials removed. Claude files untouched. Other open shells need restarting.'
}
_crap_menu() {
    local choice
    case "${1-}" in
        status) _crap_status; return;;
        configure) [ "${2-claude}" = claude ] || { printf '%s\n' 'This client adapter is not supported yet.' >&2; return 1; }; _crap_configure; return;;
        use) _crap_use "${2-}" "${3-}"; return;;
        doctor) _crap_doctor; return;;
        uninstall) _crap_uninstall; return;;
        '') ;;
        *) printf '%s\n' 'crap [status | configure claude | use claude direct|proxy | doctor | uninstall]'; return 1;;
    esac
    [ -t 0 ] || { printf '%s\n' 'The menu needs an interactive terminal. Use crap status or crap use claude direct|proxy.' >&2; return 1; }
    while :; do
        printf '\nCRAP - Client connections\n'
        _crap_status
        printf '\n1. Claude: use proxy\n2. Claude: use direct\n3. Configure Claude connection\n4. Check proxy connection\n5. Remove integration\n0. Exit\nChoose: '
        IFS= read -r choice || return
        case "$choice" in
            1) _crap_use claude proxy;; 2) _crap_use claude direct;; 3) _crap_configure;; 4) _crap_doctor;; 5) _crap_uninstall; return;; 0) return;;
        esac
    done
}
_crap_load() {
    local name definition
    for name in claude crap; do
        if alias "$name" >/dev/null 2>&1; then printf 'Existing %s alias detected; CRAP did not replace it.\n' "$name" >&2; return 1; fi
        definition=$(typeset -f "$name" 2>/dev/null)
        if [ -n "$definition" ]; then
            case "$definition" in *'_crap_claude'*|*'_crap_menu'*) ;; *) printf 'Existing %s function detected; CRAP did not replace it.\n' "$name" >&2; return 1;; esac
        fi
    done
    [ "${1-}" != check ] || return 0
    # eval here contains only literal function declarations, never user input.
    eval 'claude() { _crap_claude "$@"; }; crap() { _crap_menu "$@"; }'
}
_crap_install() {
    local shell source_file root profile executable loader
    shell=$1
    case "$shell" in bash) profile="$HOME/.bashrc";; zsh) profile="${ZDOTDIR:-$HOME}/.zshrc";; *) printf '%s\n' 'Install with: source ./crap.sh install bash (or zsh)' >&2; return 1;; esac
    if [ -n "${BASH_VERSION-}" ]; then source_file=${BASH_SOURCE[0]}; executable=$(type -P claude); elif [ -n "${ZSH_VERSION-}" ]; then eval 'source_file=${(%):-%x}'; executable=$(whence -p claude); else printf '%s\n' 'Use Bash or Zsh.' >&2; return 1; fi
    [ -n "$executable" ] && [ -x "$executable" ] || { printf '%s\n' 'Install the official Claude Code client first.' >&2; return 1; }
    root=$(_crap_root)
    case "$root$profile" in *"'"*|*'\'*|*'
'*) printf '%s\n' 'Unsupported quote, backslash or newline in installation path.' >&2; return 1;; esac
    [ ! -L "$root" ] || { printf '%s\n' 'Refusing a symlink installation directory.' >&2; return 1; }
    if [ -e "$root" ] && [ ! -O "$root" ]; then printf '%s\n' 'Installation directory belongs to another user.' >&2; return 1; fi
    # Check conflicts before writing the user's profile.
    _crap_load check || return 1
    (umask 077; mkdir -p "$root/clients/claude") || return 1
    chmod 700 "$root" "$root/clients" "$root/clients/claude" || return 1
    loader="CRAP_SHELL_HOME='$root'; . '$root/shell.sh' load # CRAP shell integration"
    if [ -f "$root/profile" ] && [ "$(cat "$root/profile")" != "$profile" ]; then printf '%s\n' 'Already installed for another shell profile. Uninstall there first.' >&2; return 1; fi
    if [ -f "$profile" ] && grep -q '# CRAP shell integration' "$profile" && ! grep -Fqx "$loader" "$profile"; then printf '%s\n' 'A different CRAP loader exists. Resolve it before installing.' >&2; return 1; fi
    if [ "$source_file" != "$root/shell.sh" ]; then
        # Strip the personalized ticket before installing the persistent script.
        (umask 077; sed '/^# CRAP enrollment payload/,$d' "$source_file" > "$root/shell.sh") || return 1
    fi
    chmod 600 "$root/shell.sh"
    _crap_write "$root/clients/claude/executable" "$executable" || return 1
    [ -f "$root/clients/claude/mode" ] || _crap_write "$root/clients/claude/mode" direct
    _crap_write "$root/profile" "$profile" && _crap_write "$root/loader" "$loader" || return 1
    if ! grep -Fqx "$loader" "$profile" 2>/dev/null; then
        [ ! -f "$profile" ] || cp "$profile" "$root/profile-backup-$(date +%s)"
        printf '\n%s\n' "$loader" >> "$profile" || return 1
    fi
    _crap_load || return 1
    printf '%s\n' 'Installed. Run crap to configure a client. New shells load it automatically.'
}
# Bash 3.2 may apply errexit inside a sourced file even when the caller checks
# its result. Catch expected failures explicitly before returning to that caller.
crap_install_result=0
case "${1-load}" in
    install) _crap_install "${2-}" || crap_install_result=$?;;
    load) _crap_load || crap_install_result=$?;;
esac
if [ "$crap_install_result" != 0 ]; then return "$crap_install_result"; fi
(exit 0)
